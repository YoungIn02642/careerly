/* 회사명 대조는 법인격 표기와 공백을 걷어내고 본다 — 같은 회사가 '삼성전자' 와
   '삼성전자(주)' 로 제각각 온다(우리 목록은 앞쪽, DART 기업개황은 뒤쪽).
   그냥 두면 리포트 화면에서만 이름 예외가 조용히 빗나간다(실측: 삼성전자가
   '컴퓨터·통신장비' 로 떴다). company-sectors.js norm 과 같은 규칙이다. */
const norm = s => String(s || '')
  .replace(/\(주\)|\(유\)|\(재\)|\(사\)|주식회사|유한회사/g, '')
  .replace(/\s+/g, '')
  .toLowerCase();
const BY_NAME_NORM = new Map(Object.entries(BY_NAME).map(([k, v]) => [norm(k), v]));

/* 긴 코드부터 짧은 코드로 내려가며 처음 맞는 규칙을 쓴다. */
function minorOfCode(code) {
  const c = String(code || '').trim();
  for (let len = Math.min(5, c.length); len >= 2; len--) {
    const hit = BY_CODE[c.slice(0, len)];
    if (hit) return hit;
  }
  return null;
}

/* 회사 하나의 업종. { major, minor } 또는 null.
   이름 예외가 코드보다 먼저다 — 예외를 둔 이유가 코드가 틀려서다. */
/* by 를 같이 돌려준다: 'name' 은 코드가 틀려서 손으로 옮긴 회사라는 뜻이다.
   "이 직무를 주로 뽑는 업종" 을 셀 때 이 회사들은 빼야 한다 — 네패스아크(업종코드 73)를
   반도체로 옮겨 뒀더니, 코드 73이 들어간 직무마다 '반도체·전자부품' 이 추천으로 붙었다. */
function classify(name, code) {
  const byName = BY_NAME[name] || BY_NAME_NORM.get(norm(name));
  const minor = byName || minorOfCode(code);
  if (!minor) return null;
  const major = MAJOR_OF.get(minor);
  if (!major) throw new Error(`분류표에 없는 중분류: ${minor} (${name})`);
  return { major, minor, by: byName ? 'name' : 'code' };
}

