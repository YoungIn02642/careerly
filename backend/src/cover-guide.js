/* ── 검사 ────────────────────────────────────────────────────────
   본문을 받아 걸리는 표현을 돌려준다. 위치(index)를 같이 주는 것은 화면에서
   해당 부분을 짚어 주기 위해서다 — "어딘가 걸렸다"만으로는 고칠 수 없다. */
function findCliches(text) {
  const body = String(text || '');
  if (!body.trim()) return [];
  const hits = [];
  for (const c of CLICHES) {
    const at = body.indexOf(c.term);
    if (at !== -1) hits.push({ term: c.term, why: c.why, at });
  }
  return hits.sort((a, b) => a.at - b.at);
}

/* AI 흔적은 '나왔다'가 아니라 '몇 번 나왔다'로 판정한다. 한 번은 자연스러운
   말이지만 세 번은 흔적이다 — 그래서 항목마다 repeat 기준을 따로 둔다. */
function findAiTells(text) {
  const body = String(text || '');
  if (!body.trim()) return [];
  const hits = [];
  for (const t of AI_TELLS) {
    /* '저는 ~라고 생각합니다' 처럼 사이가 비는 표현은 앞뒤 조각으로 나눠 센다. */
    const parts = t.term.split('~').map(s => s.trim()).filter(Boolean);
    const count = parts.length > 1
      ? Math.min(...parts.map(p => countOccurrences(body, p)))
      : countOccurrences(body, t.term);
    if (count > t.repeat) hits.push({ term: t.term, why: t.why, count });
  }
  return hits.sort((a, b) => b.count - a.count);
}

function countOccurrences(body, needle) {
  if (!needle) return 0;
  let n = 0;
  let at = body.indexOf(needle);
  while (at !== -1) { n++; at = body.indexOf(needle, at + needle.length); }
  return n;
}

/* ── 면접 예상질문 ───────────────────────────────────────────────
   "써 놓고 대비가 안 되면 못 쓴 것과 같다"는 원칙(ARCHETYPES.followup)을
   문항 단위로 확장한다. 기업 분석에서 나오는 질문 3종은 회사가 정해지면
   항상 같으므로 고정 문구로 두고, 회사명만 끼운다.

   근거가 없으면 질문을 만들지 않는다 — 뉴스를 못 받아온 상태에서
   "최근 이슈를 아느냐"고 물어봐야 학생이 답을 찾을 곳이 없다. */
function interviewQuestions({ company, hasNews = false, competencies = [] } = {}) {
  const co = String(company || '').trim();
  const name = co || '지원 회사';
  const out = [];

  if (hasNews) {
    out.push({
      q: `${name}의 최근 이슈 중 아는 것을 말해 보세요.`,
      how: '위 기사 중 하나를 골라 사실 → 그것이 회사에 갖는 의미 → 내 견해 순으로 답하세요. 기사 3건을 나열하지 마세요.',
      from: 'news',
    });
  }
  out.push({
    q: `왜 경쟁사가 아니라 ${name}인가요?`,
    how: '두 회사가 같은 시장에서 다르게 하고 있는 것 하나를 짚고, 그 차이가 내 경험과 어떻게 맞닿는지로 답하세요.',
    from: 'competitor',
  });
  out.push({
    q: `${name}가 앞으로 어느 방향으로 가야 한다고 보나요?`,
    how: '최근 움직임 하나를 근거로 들고, 그 방향에서 지원 직무가 맡을 부분까지 이어서 답하세요.',
    from: 'strategy',
  });

  /* 역량 카드에 이미 붙어 있는 followup 을 문항 질문 뒤에 이어 붙인다.
     같은 질문이 두 번 나오지 않게 문구로 중복을 거른다. */
  const seen = new Set(out.map(o => o.q));
  for (const c of competencies) {
    if (!c?.followup || seen.has(c.followup)) continue;
    seen.add(c.followup);
    out.push({ q: c.followup, how: `${c.label} 문단을 그렇게 썼다면 반드시 들어오는 질문입니다.`, from: 'competency' });
  }
  return out;
}

/* ── 첫 문장 틀 ──────────────────────────────────────────────────
   arc.openers 는 "이렇게 시작하라"는 방식 설명이고, 여기서는 그 방식에
   **내 활동 이름을 실제로 끼운 문장**을 만든다. 방식만 읽고 첫 문장을 못 쓰는
   경우가 많아서(실제로 가장 자주 막히는 지점) 한 칸 더 내려간 것이다.

   지어내지 않는 규칙:
     - 채우는 값은 우리가 아는 것뿐 — 활동명·유형·기간
     - 모르는 것은 전부 [대괄호] 로 남긴다
     - 활동이 없으면 문장을 만들지 않는다 (빈 이름으로 만든 문장은 거짓이 된다) */
const OPENING_PATTERNS = [
  {
    id: 'problem-first',
    label: '문제를 먼저 던지는 도입',
    build: a => `${a.name}에서 [무엇이 문제였는지 한 문장]이었습니다. `
      + `${a.duration ? `${a.duration} 동안 ` : ''}[내가 맡은 역할]로서 이 문제를 [목표 수치]까지 줄이는 것이 제 과제였습니다.`,
  },
  {
    id: 'number-first',
    label: '숫자를 먼저 던지는 도입',
    build: a => `[숫자]. ${a.name}에서 제가 [바꾼 것 / 다룬 규모]입니다. `
      + `이 숫자가 나오기까지 [가장 어려웠던 지점]을 넘어야 했습니다.`,
  },
  {
    id: 'wrong-first',
    label: '틀렸던 판단부터 여는 도입',
    build: a => `${a.name}을 시작할 때 저는 [처음 세운 가설]이라고 판단했고, 그 판단은 틀렸습니다. `
      + `[무엇을 확인하고 알게 됐는지]가 방향을 바꾼 계기였습니다.`,
  },
];

/* reuse 는 spreadMaterials 가 "이 소재는 앞의 다른 역량에도 배정됐다"고 표시한 것이다.
   그 표시를 여기까지 들고 와야 한다 — 안 그러면 카드마다 같은 활동으로 시작하는
   첫 문장이 나오고, 학생은 그게 중복인 줄 모른 채 두 문항에 같은 경험을 쓴다.
   (lead 문구에는 경고가 있는데 문장 틀에만 없으면, 눈에 띄는 쪽만 따라간다.) */
function openingDrafts(mine, { limit = 2, reuse = false } = {}) {
  const top = Array.isArray(mine) ? mine[0] : null;
  if (!top || !top.name) return [];
  return OPENING_PATTERNS.slice(0, limit).map(p => ({
    id: p.id,
    label: p.label,
    text: p.build(top),
    basedOn: top.name,
    reuse: Boolean(reuse),
    warn: reuse ? '이 경험은 다른 역량에도 배정돼 있어요. 문항이 여러 개라면 소재를 나눠 쓰세요.' : null,
  }));
}

/* 대괄호 빈칸이 남아 있으면 아직 제출할 수 없는 글이다. 화면이 이 수를 세어
   "빈칸 3개 남음"으로 보여준다 — 체크리스트 항목 중 유일하게 자동 판정이 되는 것. */
function countBlanks(text) {
  const m = String(text || '').match(/\[[^\]]+\]/g);
  return m ? m.length : 0;
}

