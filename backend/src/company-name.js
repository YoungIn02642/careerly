/* ════════════════════════════════════════════════════════════
   회사명 대조와 마감일 계산 — 채용공고 경로가 공유하는 규칙

   사람인·워크넷 둘 다 "회사명으로 찾기" 파라미터가 없다. 키워드로 넘기면 공고제목·
   직무내용까지 뒤져서 남의 회사 공고가 섞여 온다. 받아온 뒤 회사명을 우리가 대조하는
   수밖에 없고, 그 규칙이 두 파일에 따로 있으면 한쪽만 고쳐져 어긋난다. 여기 하나로 둔다.
   ════════════════════════════════════════════════════════════ */

/* (주)·주식회사 같은 법인격 표기와 공백을 걷어낸다. 같은 회사가
   '(주)토스' · '토스 주식회사' · '토스' 로 제각각 올라오기 때문이다.

   ── 한 글자짜리 ㈜ 를 빠뜨리고 있었다 (2026-09-06, 고용24 를 붙이며 발견) ──
   여기는 `(주)` 세 글자만 지웠는데, 실제 공고에는 **한 글자 기호 ㈜**(U+321C)와
   **전각 괄호 （주）** 도 섞여 온다. 고용24 캐시 3,851건을 세어 보니 412건(11%)이
   그 표기였다 — 그 회사들은 대조에서 **통째로 빠지고 있었다.**
   에러가 안 난다. '이 회사 공고가 없습니다' 로 조용히 나갈 뿐이라 화면만 봐서는
   자료가 없는 것과 구분되지 않는다(6-3 부류).

   그래서 **전각을 먼저 반각으로 접고** 나서 법인격을 지운다. 순서를 바꾸면
   （주） 가 (주) 가 되기 전에 지우기 규칙을 지나가서 그대로 남는다. */
/* ── 한글로 적은 영문 사명을 되돌린다 (2026-09-07, 사용자 지적) ──
   사용자가 회사 리포트를 보고 "채용공고 있는 게 없는데?" 라고 했다. 원인 하나가
   여기 있었다 — 고용24 에는 **`엘지전자`** 로 올라와 있는데 우리 목록(DART)은
   `LG전자` 다. 글자가 달라 대조가 통째로 빗나갔고, 화면에는 그냥 '공고 없음' 으로
   나갔다(에러가 안 나는 부류다).

   ── 왜 이 방식이 안전한가 ──
   대조는 **정규화한 문자열이 정확히 같을 때만** 통과한다. 그래서 다른 낱말 안에
   우연히 든 '엘지'(임마누엘지역아동센터 → 임마누lg역아동센터)가 바뀌어도 'lg전자'
   와 같아지지 않는다. 부분 일치를 허용하지 않는 한 이 치환은 오탐을 만들지 않는다.

   ── 표에 없는 것을 추측하지 않는다 ──
   실제로 두 표기가 다 관측된 그룹만 적는다. '한화'·'두산'처럼 원래 한글인 이름은
   넣을 것이 없고, 억지로 넣으면 엉뚱한 회사를 붙인다(25-3 과 같은 원칙). */
const ROMAN = [
  [/엘지/g, 'lg'], [/에스케이/g, 'sk'], [/씨제이/g, 'cj'], [/지에스/g, 'gs'],
  [/케이티/g, 'kt'], [/엘에스/g, 'ls'], [/에이치디/g, 'hd'], [/에스티/g, 'st'],
  [/디비/g, 'db'], [/오씨아이/g, 'oci'], [/케이씨씨/g, 'kcc'], [/에이치엘/g, 'hl'],
];

function normalize(s) {
  const base = String(s || '')
    .replace(/[（）]/g, m => (m === '（' ? '(' : ')'))
    .replace(/㈜/g, '')                     // 한 글자 기호 — (주) 와 같은 뜻이다
    .replace(/㈔/g, '')                     // 사단법인
    .replace(/\(주\)|\(유\)|\(재\)|\(사\)|주식회사|유한회사|재단법인|사단법인/g, '')
    .replace(/\s+/g, '')
    .toLowerCase();
  /* 소문자로 만든 **뒤에** 치환한다 — 바꿔 넣는 값이 소문자라 순서를 바꾸면
     'LG' 와 'lg' 가 갈린다. */
  return ROMAN.reduce((acc, [re, to]) => acc.replace(re, to), base);
}

/* **정확히 같을 때만** 같은 회사로 본다.
   부분 문자열을 허용하면 '토스' 로 찾을 때 '대한토스트' 가 걸리고, '삼성전자' 에
   '삼성전자로지텍' 이 걸린다. 남의 회사 공고를 자기 지원 회사 것으로 알고 자소서에
   붙여넣는 쪽이, 공고 몇 건을 놓치는 쪽보다 훨씬 나쁘다. 못 찾은 공고는 화면의
   '사람인에서 더 찾기' 링크가 받는다. */
function sameCompany(a, b) {
  const x = normalize(a);
  const y = normalize(b);
  if (!x || !y) return false;
  return x === y;
}

/* 마감일 → D-n. **달력 날짜 차이**로 센다.
   시각으로 빼면 오늘 마감인 공고가 D-1 로 나온다(자정까지 남은 시간이 0보다 크므로
   올림에서 1이 된다). 마감 당일은 D-0 이어야 한다.
   이미 지난 공고는 null — D-(-3) 을 띄우면 아직 지원할 수 있는 것처럼 보인다.

   들어오는 모양이 두 가지다: 워크넷은 'YYYYMMDD', 사람인은 ISO('2026-08-20T23:59:59+09:00').
   숫자만 뽑아 앞 8자리를 쓰면 둘 다 읽힌다. */
function dday(raw) {
  const s = String(raw || '').replace(/\D/g, '').slice(0, 8);
  if (s.length !== 8) return null;
  const y = Number(s.slice(0, 4)), m = Number(s.slice(4, 6)), d = Number(s.slice(6, 8));
  const end = new Date(y, m - 1, d);
  if (Number.isNaN(end.getTime()) || end.getMonth() !== m - 1) return null;   // 20261352 방어
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const days = Math.round((end.getTime() - today.getTime()) / 86400000);
  return days >= 0 ? days : null;
}

module.exports = { normalize, sameCompany, dday };
