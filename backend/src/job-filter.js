const isExcludedMiddle = code => EXCLUDED_MIDDLES.has(String(code));
const isExcludedJob = name => EXCLUDED_JOBS.has(String(name).trim());

/* 트리에서 걸러낸 사본을 돌려준다. 원본은 건드리지 않는다 —
   호출부가 캐시된 트리를 그대로 들고 있는 경우가 있어서(catalog-db 의 _jobTree),
   제자리에서 고치면 두 번 부를 때 결과가 달라진다. */
function filterTree(tree) {
  if (!tree || tree.empty || !Array.isArray(tree.majors)) return tree;

  const majors = tree.majors
    .map(M => ({
      ...M,
      ...(MAJOR_RENAMES.get(String(M.code)) || {}),
      middles: (M.middles || [])
        .filter(m => !isExcludedMiddle(m.code))
        .map(m => ({ ...m, jobs: (m.jobs || []).filter(j => !isExcludedJob(j.name)) })),
    }))
    /* 2차 분류가 하나도 안 남은 1차는 통째로 뺀다. 빈 대분류를 남기면 화면에
       눌러도 아무것도 없는 칸이 생긴다(건설·채굴직, 설치·정비·생산직, 농림어업직). */
    .filter(M => M.middles.length > 0);

  return {
    ...tree,
    majors,
    counts: {
      majors: majors.length,
      middles: majors.reduce((s, M) => s + M.middles.length, 0),
      jobs: majors.reduce((s, M) => s + M.middles.reduce((t, m) => t + m.jobs.length, 0), 0),
    },
  };
}

/* 제외 목록이 실제 데이터와 맞는지 확인한다. 이름을 하나라도 잘못 적으면
   그 직업은 조용히 계속 노출된다 — 에러가 안 나므로 눈으로는 못 찾는다. */
function verify(tree) {
  const middleCodes = new Set();
  const jobNames = new Set();
  (tree?.majors || []).forEach(M => (M.middles || []).forEach(m => {
    middleCodes.add(String(m.code));
    (m.jobs || []).forEach(j => jobNames.add(String(j.name).trim()));
  }));

  return {
    unknownMiddles: [...EXCLUDED_MIDDLES.keys()].filter(c => !middleCodes.has(c)),
    unknownJobs: [...EXCLUDED_JOBS.keys()].filter(n => !jobNames.has(n)),
  };
}

