/* job-groups.js 의 norm 과 같은 규칙 — 두 곳이 다르면 매칭이 갈린다. */
const norm = s => String(s ?? '').replace(/[\s·ㆍ,()（）]/g, '').toLowerCase();

const HIDDEN_JOBS = new Set(HIDDEN_JOB_NAMES.map(norm));

const isHiddenMiddle = code => HIDDEN_MIDDLES.has(String(code));
const isHiddenJob = name => HIDDEN_JOBS.has(norm(name));

module.exports = {
  HIDDEN_MIDDLES, HIDDEN_JOB_NAMES, HIDDEN_JOBS,
  isHiddenMiddle, isHiddenJob, norm,
};
